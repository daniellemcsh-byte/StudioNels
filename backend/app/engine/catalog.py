def _all_models() -> list[dict[str, Any]]:
    """Built-in catalog + user-added customs + Diffusers mirrors + Wan2GP ckpts."""
    by_id = {m["id"]: dict(m) for m in MODELS}
    known_hf = {str(m.get("hf_id")) for m in MODELS if m.get("hf_id")}
    try:
        from .custom_models import discover_local_models, list_custom_models

        for m in list_custom_models():
            by_id[m["id"]] = m
            if m.get("hf_id"):
                known_hf.add(str(m["hf_id"]))
        for m in discover_local_models(known_hf):
            matched = next((x for x in by_id.values() if x.get("hf_id") == m.get("hf_id")), None)
            if matched:
                matched["local_path"] = m.get("local_path")
            else:
                by_id[m["id"]] = m
                if m.get("hf_id"):
                    known_hf.add(str(m["hf_id"]))
    except Exception:
        pass
    try:
        from .wan2gp_ckpts import scan_wan2gp_ckpts

        for m in scan_wan2gp_ckpts():
            existing = by_id.get(m["id"])
            if existing:
                existing.update({k: v for k, v in m.items() if v is not None})
            else:
                by_id[m["id"]] = m
            if m.get("hf_id"):
                known_hf.add(str(m["hf_id"]))
    except Exception:
        pass
    try:
        from .wan2gp_assets import (
            scan_audio_models,
            scan_image_models,
            scan_upsample_models,
            scan_video_models,
        )

        for m in (
            scan_video_models()
            + scan_image_models()
            + scan_audio_models()
            + scan_upsample_models()
        ):
            existing = by_id.get(m["id"])
            if existing:
                existing.update({k: v for k, v in m.items() if v is not None})
            else:
                by_id[m["id"]] = m
            if m.get("hf_id"):
                known_hf.add(str(m["hf_id"]))
    except Exception:
        pass
    # Wan2GP engine-only architectures are no longer merged into the Generate catalog.
    # StudioNels uses its own Diffusers downloads (hf_id) — Import Wan2GP is optional/legacy.
    return list(by_id.values())


def _is_studionels_runnable(m: dict[str, Any]) -> bool:
    """Models Generate can run without Wan2GP (have Diffusers / local weights)."""
    if str(m.get("format") or "") == "wan2gp-engine":
        return False
    if str(m.get("id") or "").startswith("wgp-"):
        return False
    if m.get("wan2gp") and not m.get("hf_id") and not m.get("local_path"):
        return False
    return True


def list_models_for_mode(mode: str) -> list[dict[str, Any]]:
    return [m for m in _all_models() if mode in m["modes"] and _is_studionels_runnable(m)]


def get_model(model_id: str) -> dict[str, Any] | None:
    for m in _all_models():
        if m["id"] == model_id:
            return m
    return None


def default_model_for_mode(mode: str, target_vram_gb: float = 8) -> dict[str, Any] | None:
    candidates = list_models_for_mode(mode)
    fit = [m for m in candidates if m["min_vram_gb"] <= target_vram_gb]
    pool = fit or candidates
    # Prefer fast distilled / 1.3B models — matches how other local apps feel snappy
    def _speed_key(m: dict[str, Any]) -> tuple:
        mid = str(m.get("id") or "").lower()
        label = str(m.get("label") or "").lower()
        distilled = 0 if (m.get("distilled") or "distill" in mid or "distill" in label) else 1
        small = 0 if ("1.3" in mid or "1.3" in label or "schnell" in mid) else 1
        return (distilled, small, float(m.get("min_vram_gb") or 0), mid)

    pool = sorted(pool, key=_speed_key)
    return pool[0] if pool else None
